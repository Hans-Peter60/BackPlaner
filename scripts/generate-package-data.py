#!/usr/bin/env python3
"""Writes the data BakePlannerCore needs where it cannot read the app's
bundle (Android): the translations of its texts and the bundled units.

    python3 scripts/generate-package-data.py          # rewrite the files
    python3 scripts/generate-package-data.py --check  # exit 1 if they are stale

Sources, both in the app:
- BackPlaner/Localizable.xcstrings: every text the package shows
  (String(localized: …) in its sources) and every unit name (unit.*), in
  the languages the catalog has.
- BackPlaner/DataFiles/UnitSets.json: the units the app ships with.

On iOS the package reads both from the app's bundle as before; the
generated files are only used elsewhere. check-repo.py runs --check.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "BackPlaner/Localizable.xcstrings"
UNIT_SETS = ROOT / "BackPlaner/DataFiles/UnitSets.json"
OUTPUT = ROOT / "BakePlannerCore/Sources/BakePlannerCore/Generated"
TRANSLATIONS = OUTPUT / "PackageTranslations.swift"
BUNDLED_UNITS = OUTPUT / "BundledUnitSetsData.swift"

HEADER = "// Generated by scripts/generate-package-data.py from {source}. Do not edit;\n// run the script after changing the source."


def check_repo():
    spec = importlib.util.spec_from_file_location("check_repo", ROOT / "scripts/check-repo.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def swift_literal(text: str) -> str:
    out = []
    for character in text:
        if character == "\\":
            out.append("\\\\")
        elif character == '"':
            out.append('\\"')
        elif character == "\n":
            out.append("\\n")
        elif character == "\t":
            out.append("\\t")
        elif character == "\r":
            out.append("\\r")
        elif ord(character) < 0x20:
            out.append("\\u{%x}" % ord(character))
        else:
            out.append(character)
    return '"' + "".join(out) + '"'


def value_of(localization: dict) -> str | None:
    unit = localization.get("stringUnit")
    if unit and unit.get("value"):
        return unit["value"]
    # A text with plural forms: the general one.
    plural = localization.get("variations", {}).get("plural", {})
    other = plural.get("other", {}).get("stringUnit", {})
    return other.get("value")


def translations_source() -> str:
    repo = check_repo()
    strings = json.loads(CATALOG.read_text(encoding="utf-8"))["strings"]

    keys = set(key for key in strings if key.startswith("unit."))
    for path in sorted((ROOT / repo.PACKAGE_SOURCES).rglob("*.swift")):
        if path.parent == OUTPUT:
            continue
        for match in repo.LOCALIZED_LITERAL.finditer(path.read_text(encoding="utf-8")):
            pattern = repo.catalog_key_pattern(match.group(1))
            keys.update(key for key in strings if pattern.match(key))

    lines = [HEADER.format(source="BackPlaner/Localizable.xcstrings"), "",
             "/// The package's texts and unit names by catalog key and language.",
             "enum PackageTranslations {",
             "    static let table: [String: [String: String]] = ["]
    for key in sorted(keys):
        values = {}
        for language, localization in sorted(strings[key].get("localizations", {}).items()):
            value = value_of(localization)
            if value is not None:
                values[language] = value
        if not values:
            continue
        entries = ", ".join(f"{swift_literal(language)}: {swift_literal(value)}" for language, value in values.items())
        lines.append(f"        {swift_literal(key)}: [{entries}],")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def bundled_units_source() -> str:
    text = UNIT_SETS.read_text(encoding="utf-8")
    json.loads(text)  # fails loudly on a broken file
    assert '"""#' not in text
    return "\n".join([
        HEADER.format(source="BackPlaner/DataFiles/UnitSets.json"), "",
        "/// The units the app ships with, as UnitSets.json holds them.",
        "enum BundledUnitSetsData {",
        '    static let json = #"""',
        text.rstrip("\n"),
        '"""#',
        "}",
        "",
    ])


def main() -> int:
    files = {TRANSLATIONS: translations_source(), BUNDLED_UNITS: bundled_units_source()}
    if "--check" in sys.argv:
        stale = [path for path, content in files.items()
                 if not path.exists() or path.read_text(encoding="utf-8") != content]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date — run python3 scripts/generate-package-data.py")
        return 1 if stale else 0
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for path, content in files.items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
